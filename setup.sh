#!/usr/bin/env bash
# =============================================================================
# Homelab Tier 1 stack — one-time setup (run ON THE IMAC, inside this folder)
#   ./setup.sh                auto-detects the iMac's LAN IP
#   ./setup.sh 192.168.1.191  use this IP instead (if auto-detect picks wrong)
#
# What it does:
#   1. Creates all data folders.
#   2. Writes .env with your IP, your user id, and freshly generated secrets
#      (openssl, on this machine — nothing is printed except where to find it,
#      and nothing leaves the iMac). Refuses to overwrite an existing .env.
#   3. Puts the same IP into Homepage's service links.
# Safe to re-run: if .env already exists it stops after creating folders.
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")"

# --- folders -----------------------------------------------------------------
mkdir -p data/ntfy data/healthchecks data/changedetection data/vaultwarden \
         data/syncthing data/stirling/tessdata data/stirling/configs \
         data/stirling/logs data/stirling/pipeline data/karakeep \
         data/adguard/work data/adguard/conf \
         sync paperless/consume paperless/export homepage/config

# --- .env --------------------------------------------------------------------
if [ -f .env ]; then
  echo ".env already exists — leaving it untouched."
  echo "To start over: rm .env  (this does NOT delete any app data in ./data)"
  exit 0
fi

IMAC_IP="${1:-}"
if [ -z "$IMAC_IP" ]; then
  # `hostname -I` does not exist on this Arch box — fall back to the
  # source address of the default route (the LAN IP).
  IMAC_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
fi
if [ -z "$IMAC_IP" ]; then
  IMAC_IP="$(ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.*src \([0-9.]*\).*/\1/p')"
fi
if [ -z "$IMAC_IP" ]; then
  echo "Could not detect an IP. Re-run with one:  ./setup.sh 192.168.1.191" >&2
  exit 1
fi
PUID_VAL="$(id -u)"
PGID_VAL="$(id -g)"
# If Tailscale is up, Homepage should also answer on the tailnet address.
TS_IP="$(tailscale ip -4 2>/dev/null | head -n 1 || true)"
EXTRA_HOSTS=""
[ -n "$TS_IP" ] && EXTRA_HOSTS=",${TS_IP}:3000,homelab:3000"

gen() { openssl rand -hex 32; }

umask 077
cat > .env <<EOF
# Generated by setup.sh on $(date '+%Y-%m-%d') — chmod 600, never commit/share.
TZ=America/New_York
IMAC_IP=${IMAC_IP}
PUID=${PUID_VAL}
PGID=${PGID_VAL}
HOMEPAGE_ALLOWED_HOSTS=${IMAC_IP}:3000${EXTRA_HOSTS},localhost:3000,127.0.0.1:3000

# Healthchecks (login: the email below + this password — change it in the UI)
HC_SECRET_KEY=$(gen)
HC_SUPERUSER_EMAIL=dvaughnhouse@gmail.com
HC_SUPERUSER_PASSWORD=$(openssl rand -base64 18)

# Vaultwarden (ADMIN_TOKEN unlocks the /admin page — treat like a root password)
VW_ADMIN_TOKEN=$(gen)
VW_SIGNUPS_ALLOWED=true

# Paperless-ngx (profile: docs)
PAPERLESS_SECRET_KEY=$(gen)
PAPERLESS_DB_PASSWORD=$(gen)
PAPERLESS_ADMIN_USER=dvaughn
PAPERLESS_ADMIN_PASSWORD=$(openssl rand -base64 18)

# Karakeep (profile: tools)
KARAKEEP_VERSION=release
MEILI_MASTER_KEY=$(gen)
NEXTAUTH_SECRET=$(gen)
# AI tagging (optional): if Ollama serves on the Mac Studio, uncomment and
# set its LAN IP, then re-run: docker compose --profile tools up -d
# OLLAMA_BASE_URL=http://<MAC_STUDIO_IP>:11434
OLLAMA_BASE_URL=
EOF
chmod 600 .env

# --- homepage links get the real IP ------------------------------------------
sed -i "s/__IMAC_IP__/${IMAC_IP}/g" homepage/config/services.yaml

echo ""
echo "Done. Your stack lives at http://${IMAC_IP}:3000 (Homepage) once started."
echo "Secrets and first-login passwords are in .env (keep it private)."
echo "Next:  docker compose pull && docker compose up -d"
